#!/usr/bin/env node
// Cmail — single-file worker build
// 1) embeds every file from public/ into src/generated/assets.ts
//    (the worker then serves its own UI — no "assets" binding, no folder upload)
// 2) turns schema.sql into src/generated/schema.ts (statement list for
//    the one-click "initialize tables" endpoint, plus healing ALTERs)
// 3) bundles src/worker.ts with esbuild → dist-worker/worker.js → root worker.js
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, rmSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const PUB = join(ROOT, 'public');
const GEN = join(ROOT, 'src', 'generated');

// ---------- helpers ----------
const djb2 = (s) => {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return 'W/' + h.toString(36) + '-' + s.length.toString(36);
};

const TEXT_EXT = new Set(['.html', '.css', '.js', '.mjs', '.json', '.txt', '.svg', '.map']);
const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.map': 'application/json; charset=utf-8',
  '.woff2': 'font/woff2',
};

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// ---------- 1) embedded assets ----------
const files = walk(PUB);
const entries = [];
for (const p of files) {
  const key = relative(PUB, p).split('\\').join('/');
  const ext = extname(p).toLowerCase();
  const type = MIME[ext];
  if (!type) throw new Error(`no mime for ${key}`);
  const buf = readFileSync(p);
  const tag = djb2(buf.toString('latin1'));
  if (TEXT_EXT.has(ext)) {
    entries.push({ key, text: buf.toString('utf8'), type, tag });
  } else {
    entries.push({ key, b64: buf.toString('base64'), type, tag });
  }
}

mkdirSync(GEN, { recursive: true });
const assetsTs = `// AUTO-GENERATED by scripts/build-worker.mjs — do not edit by hand.
// Every UI file lives inside the worker: one paste, one binding, nothing else.
export type EmbeddedAsset = { text?: string; b64?: string; type: string; tag: string };

export const ASSET_FILES: Record<string, EmbeddedAsset> = {
${entries.map((e) => {
  const body = e.text !== undefined
    ? `text: ${JSON.stringify(e.text)}`
    : `b64: ${JSON.stringify(e.b64)}`;
  return `  ${JSON.stringify(e.key)}: { ${body}, type: ${JSON.stringify(e.type)}, tag: ${JSON.stringify(e.tag)} },`;
}).join('\n')}
};
`;
writeFileSync(join(GEN, 'assets.ts'), assetsTs);

// ---------- 2) schema statements ----------
const schemaSql = readFileSync(join(ROOT, 'schema.sql'), 'utf8');
const clean = (chunk) =>
  chunk
    .split('\n')
    .filter((l) => !l.trim().startsWith('--'))
    .join('\n')
    .trim();

const statements = schemaSql
  .split(';')
  .map(clean)
  .filter((s) => s.length > 0)
  .map((sql, i) => ({ name: `stmt_${String(i + 1).padStart(2, '0')}`, sql, optional: false }));

// healing statements: bring databases created by older releases up to date.
// they fail harmlessly ("duplicate column") on fresh installs → marked optional.
const healing = [];
for (const m of ['migrations/0002_mailbox_identity.sql', 'migrations/0003_vault_folders.sql']) {
  const sql = readFileSync(join(ROOT, m), 'utf8');
  for (const st of sql.split(';').map(clean)) {
    if (/^ALTER TABLE/i.test(st)) healing.push({ name: `heal_${healing.length + 1}`, sql: st, optional: true });
  }
}

const schemaTs = `// AUTO-GENERATED by scripts/build-worker.mjs — do not edit by hand.
// Full database schema: statements run in order by POST /api/setup/init.
// "optional" statements heal older installs and may fail harmlessly.
export type SchemaStatement = { name: string; sql: string; optional: boolean };

export const SCHEMA: SchemaStatement[] = [
${[...statements, ...healing]
  .map((s) => `  { name: ${JSON.stringify(s.name)}, optional: ${s.optional}, sql: ${JSON.stringify(s.sql)} },`)
  .join('\n')}
];
`;
writeFileSync(join(GEN, 'schema.ts'), schemaTs);

// ---------- 3) bundle ----------
rmSync(join(ROOT, 'dist-worker'), { recursive: true, force: true });
mkdirSync(join(ROOT, 'dist-worker'), { recursive: true });
execSync(
  'npx esbuild src/worker.ts --bundle --format=esm --target=es2022 --legal-comments=none --outfile=dist-worker/worker.js',
  { cwd: ROOT, stdio: 'inherit' },
);
copyFileSync(join(ROOT, 'dist-worker', 'worker.js'), join(ROOT, 'worker.js'));

const kb = (p) => (statSync(p).size / 1024).toFixed(1) + ' KB';
console.log('');
console.log('assets embedded :', entries.length, 'files');
console.log('schema stmts    :', statements.length, '+', healing.length, 'healing (optional)');
console.log('dist-worker     :', kb(join(ROOT, 'dist-worker/worker.js')));
console.log('root worker.js  :', kb(join(ROOT, 'worker.js')));
